function normalizeOverviewBlocks(project) {
  const blocks = [];

  (project.overview || []).forEach((text, index) => {
    blocks.push({
      text,
      images: index === 0 && project.overviewImage ? [project.overviewImage] : []
    });
  });

  if (project.eventScale && project.eventScale.length > 0) {
    blocks.push({
      title: "Event Scale",
      text: project.eventScale.join("\n"),
      images: project.eventScaleImage ? [project.eventScaleImage] : [],
      variant: "eventScale"
    });
  }

  if (project.impactHeading) {
    blocks.push({
      title: project.impactHeading,
      text: project.impactHeading,
      images: [],
      variant: "impactHeading"
    });
  }

  if (project.impactMetrics && project.impactMetrics.length > 0) {
    project.impactMetrics.forEach((metric) => {
      blocks.push({
        text: metric,
        images: [],
        variant: "metric"
      });
    });
  }

  if (project.overviewImpactImages && project.overviewImpactImages.length > 0) {
    blocks.push({
      images: project.overviewImpactImages
        .map((url) => sanitizeProjectImageUrl(project, url))
        .filter(Boolean),
      variant: "impactVisuals"
    });
  }

  return blocks;
}

function sanitizeProjectImageUrl(project, url) {
  if (!url) return "";

  const forbiddenBySlug = {
    "gm-vietnam": [
      "6ec183_44f21c603cfa447bad2d99eefa2294bc",
      "6ec183_a8239720041d4c97a532608070c02737",
      "6ec183_714352ed05204fc7aa8ee4432530aeb4"
    ],
    ancient8: [],
    space3: [],
    "kyros-ventures": [],
    "lilquid-nft": [],
    "arkai-nft": []
  };

  const forbiddenTokens = forbiddenBySlug[project.slug] || [];
  const isForbidden = forbiddenTokens.some((token) => url.includes(token));
  return isForbidden ? "" : url;
}

function normalizeGalleryBlocks(project) {
  return (project.galleryImages || []).map((item) => ({
    text: item.caption || "",
    images: sanitizeProjectImageUrl(project, item.url) ? [sanitizeProjectImageUrl(project, item.url)] : []
  }));
}

function normalizeRoleBlocks(project) {
  if (project.roleIntro || (project.roleBullets && project.roleBullets.length > 0) || project.roleClosing) {
    const blocks = [];

    if (project.roleIntro) {
      blocks.push({
        text: project.roleIntro,
        variant: "intro",
        images: []
      });
    }

    (project.roleBullets || []).forEach((item) => {
      blocks.push({
        text: item,
        variant: "bullet",
        images: []
      });
    });

    if (project.roleClosing) {
      blocks.push({
        text: project.roleClosing,
        variant: "closing",
        images: []
      });
    }

    return blocks;
  }

  return (project.roleDetails || []).map((item, index) => ({
    text: item,
    images:
      index === 0
        ? (project.roleImages || [])
            .map((url) => sanitizeProjectImageUrl(project, url))
            .filter(Boolean)
        : [],
    variant: "bullet"
  }));
}

function normalizeHighlightBlocks(project) {
  return (project.keyHighlightNumbers || []).map((item) => ({
    value: item.value,
    text: item.label
  }));
}

function normalizeKeyAchievementSection(project) {
  if (!project.keyAchievement) return null;

  const row1Image = sanitizeProjectImageUrl(project, project.keyAchievement.row1?.image || "");
  const row2Left = sanitizeProjectImageUrl(project, project.keyAchievement.row2?.leftImage || "");
  const row2Right = sanitizeProjectImageUrl(project, project.keyAchievement.row2?.rightImage || "");
  const row4Image = sanitizeProjectImageUrl(project, project.keyAchievement.row4?.image || "");
  const rightImages = (project.keyAchievement.rightImages || [])
    .map((url) => sanitizeProjectImageUrl(project, url))
    .filter(Boolean);

  return {
    id: "key-achievement",
    eyebrow: "03",
    title: "KEY ACHIEVEMENT",
    blocks: [
      {
        variant: "keyAchievement",
        metricCards: project.keyAchievement.metricCards || [],
        row1Lines: project.keyAchievement.row1?.lines || [],
        row1Image,
        row2Left,
        row2Right,
        row3Highlights: project.keyAchievement.row3?.highlights || [],
        row4Image,
        rightImages
      }
    ]
  };
}

